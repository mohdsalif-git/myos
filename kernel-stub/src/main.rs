/// Kernel entry point adhering to System V AMD64 ABI.
/// The bootloader jumps here with RDI = *const BootInfo.
#[no_mangle]
pub extern "sysv64" fn _start(info: *const BootInfo) -> ! {
    if info.is_null() {
        halt();
    }

    // SAFETY: Bootloader guarantees `info` is a valid BootInfo structure.
    let boot_info = unsafe { &*info };
    if boot_info.magic != BOOTINFO_MAGIC {
        halt();
    }

    let fb = &boot_info.framebuffer;
    let fb_ptr = fb.base_address as *mut u8;

    // Draw string: "Stage 2 Kernel Stub Active! Handoff Successful." at y = 200
    draw_string(fb_ptr, fb.stride, fb.width, fb.height, fb.pixel_format, 40, 200, "Stage 2 Kernel Stub Active! Handoff Successful.", 0, 240, 255);

    halt();
}

fn put_pixel(base: *mut u8, stride: u32, width: u32, height: u32, format: PixelFormat, x: u32, y: u32, r: u8, g: u8, b: u8) {
    if x >= width || y >= height {
        return;
    }
    let offset = (y as usize * stride as usize + x as usize) * 4;
    unsafe {
        let p = base.add(offset);
        match format {
            PixelFormat::Rgb => {
                *p.add(0) = r;
                *p.add(1) = g;
                *p.add(2) = b;
                *p.add(3) = 0;
            }
            PixelFormat::Bgr => {
                *p.add(0) = b;
                *p.add(1) = g;
                *p.add(2) = r;
                *p.add(3) = 0;
            }
            PixelFormat::Bitmask => {
                *(p as *mut u32) = (r as u32) | ((g as u32) << 8) | ((b as u32) << 16);
            }
        }
    }
}

fn draw_string(base: *mut u8, stride: u32, width: u32, height: u32, format: PixelFormat, mut x: u32, y: u32, s: &str, r: u8, g: u8, b: u8) {
    for &byte in s.as_bytes() {
        let glyph = get_glyph(byte);
        for (row_idx, &row_byte) in glyph.iter().enumerate() {
            for col_idx in 0..8 {
                if (row_byte & (0x80 >> col_idx)) != 0 {
                    put_pixel(base, stride, width, height, format, x + col_idx as u32, y + row_idx as u32, r, g, b);
                }
            }
        }
        x += 8;
    }
}

fn halt() -> ! {
    loop {
        unsafe {
            core::arch::asm!("cli", "hlt", options(nomem, nostack, preserves_flags));
        }
    }
}

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    halt();
}
